#!/usr/bin/env python3
"""Builds src/map/Course.rbxmx — the static part of the simple canyon — so it shows up in
Workspace in Edit mode (Rojo syncs it to Workspace.Course).

Run from the repo root:  python3 tools/build_course.py

Keep the numbers below in step with src/shared/Config/MapConfig.luau (MapService reads the
same values to place cover). The per-round cover is still generated by MapService into
Course.Cover while the game runs.
"""
import os
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "map", "Course.rbxmx")

# --- mirror of MapConfig.luau
ORIGIN = (600.0, 0.0, 0.0)
LENGTH = 1200.0
WIDTH = 170.0
WALL_HEIGHT = 60.0
COLORS = {
    "Floor": (92, 84, 76),
    "Wall": (110, 90, 72),
    "Bunker": (70, 75, 85),
    "Gate": (235, 225, 200),
    "Barrier": (56, 189, 248),
    "Sanctuary": (80, 255, 140),
}

# Roblox Enum.Material values
MATERIAL = {"Slate": 800, "Rock": 896, "Concrete": 816, "ForceField": 1584, "Marble": 784}

_ref = 0


def ref():
    global _ref
    _ref += 1
    return f"RBXCOURSE{_ref:04d}"


def prop(props, kind, name, text=None):
    el = ET.SubElement(props, kind, {"name": name})
    if text is not None:
        el.text = str(text)
    return el


def part(parent, name, size, pos, color, material, transparency=0.0, can_collide=True, can_query=True, shape=1):
    item = ET.SubElement(parent, "Item", {"class": "Part", "referent": ref()})
    props = ET.SubElement(item, "Properties")
    prop(props, "string", "Name", name)
    prop(props, "bool", "Anchored", "true")
    prop(props, "bool", "CanCollide", "true" if can_collide else "false")
    prop(props, "bool", "CanQuery", "true" if can_query else "false")
    prop(props, "bool", "CanTouch", "true")
    prop(props, "bool", "CastShadow", "true")
    prop(props, "float", "Transparency", transparency)
    prop(props, "token", "Material", MATERIAL[material])
    r, g, b = color
    prop(props, "Color3uint8", "Color3uint8", 0xFF000000 + (r << 16) + (g << 8) + b)
    prop(props, "token", "shape", shape)
    prop(props, "token", "TopSurface", 0)
    prop(props, "token", "BottomSurface", 0)
    size_el = prop(props, "Vector3", "size")
    for axis, value in zip("XYZ", size):
        ET.SubElement(size_el, axis).text = repr(float(value))
    cf = prop(props, "CoordinateFrame", "CFrame")
    for axis, value in zip("XYZ", pos):
        ET.SubElement(cf, axis).text = repr(float(value))
    for key, value in zip(["R00", "R01", "R02", "R10", "R11", "R12", "R20", "R21", "R22"], [1, 0, 0, 0, 1, 0, 0, 0, 1]):
        ET.SubElement(cf, key).text = str(value)
    return item


def main():
    ox, oy, oz = ORIGIN
    root = ET.Element("roblox", {"version": "4"})
    model = ET.SubElement(root, "Item", {"class": "Model", "referent": ref()})
    props = ET.SubElement(model, "Properties")
    prop(props, "string", "Name", "Course")

    # Floor and canyon walls
    center_z = oz - LENGTH / 2 + 30
    part(model, "Floor", (WIDTH, 4, LENGTH + 120), (ox, oy - 2, center_z), COLORS["Floor"], "Slate")
    for side in (-1, 1):
        part(model, "Wall", (12, WALL_HEIGHT, LENGTH + 120), (ox + side * (WIDTH / 2 + 6), oy - 2 + WALL_HEIGHT / 2, center_z), COLORS["Wall"], "Rock")

    # Start bunker, barrier and spawn point
    start_z = oz + 40
    part(model, "BunkerBack", (WIDTH, 30, 6), (ox, oy + 15, start_z + 40), COLORS["Bunker"], "Concrete")
    part(model, "BunkerRoof", (WIDTH, 2, 46), (ox, oy + 30, start_z + 18), COLORS["Bunker"], "Concrete")
    part(model, "StartBarrier", (WIDTH, 30, 2), (ox, oy + 15, oz), COLORS["Barrier"], "ForceField", transparency=0.5)
    part(model, "StartSpawn", (30, 1, 20), (ox, oy + 0.5, start_z + 15), COLORS["Floor"], "Slate", transparency=1, can_collide=False, can_query=False)

    # Sanctuary gate and finish zone
    end_z = oz - LENGTH
    for side in (-1, 1):
        part(model, "GatePillar", (8, 40, 8), (ox + side * 30, oy + 20, end_z), COLORS["Gate"], "Marble")
    part(model, "GateArch", (68, 6, 8), (ox, oy + 43, end_z), COLORS["Gate"], "Marble")
    part(model, "Sanctuary", (WIDTH, 30, 30), (ox, oy + 15, end_z - 20), COLORS["Sanctuary"], "ForceField", transparency=0.6, can_collide=False, can_query=False)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    ET.indent(root, space="\t")
    ET.ElementTree(root).write(OUT, encoding="utf-8", xml_declaration=False)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
